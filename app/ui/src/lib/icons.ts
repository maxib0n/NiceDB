export function commandIcon(id: string, own?: Icon): Icon {
  if (own) return own;
  const named = COMMAND_ICON[id];
  if (named) return named;
  const tool = id.startsWith('tool.') ? TOOL_ICON[id.slice(5) as ToolKind] : undefined;
  if (tool) return tool;
  if (id.startsWith('schema.gen_')) return ICON.generateSql;
  if (id.startsWith('conn.from_model.')) return CopyPlus;
  return ICON.command;
}
